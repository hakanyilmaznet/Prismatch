function normalize_lang($raw) {
  $raw = trim($raw);
  if ($raw === '') return 'en';
  $raw = str_replace('_', '-', $raw);
  if (stripos($raw, 'zh') === 0) return 'zh-CN';
  $parts = explode('-', $raw);
  return isset($parts[0]) ? $parts[0] : 'en';
}

function detect_browser_lang() {
  $supported = array_keys(supported_languages());
  $al = isset($_SERVER['HTTP_ACCEPT_LANGUAGE']) ? $_SERVER['HTTP_ACCEPT_LANGUAGE'] : '';
  if ($al) {
    $cands = explode(',', $al);
    foreach ($cands as $c) {
      $code = trim(explode(';', $c)[0]);
      if ($code === '') continue;
      if (in_array($code, $supported, true)) return $code;
      $base = normalize_lang($code);
      if (in_array($base, $supported, true)) return $base;
    }
  }
  return 'en';
}

function get_lang() {
  $supported = array_keys(supported_languages());
  if (!empty($_SESSION['lang']) && in_array($_SESSION['lang'], $supported, true)) return $_SESSION['lang'];
  if (!empty($_COOKIE['lang']) && in_array($_COOKIE['lang'], $supported, true)) {
    $_SESSION['lang'] = $_COOKIE['lang'];
    return $_COOKIE['lang'];
  }
  $l = detect_browser_lang();
  $_SESSION['lang'] = $l;
  return $l;
}

function set_lang($lang) {
  $supported = array_keys(supported_languages());
  if (!in_array($lang, $supported, true)) $lang = 'en';
  $_SESSION['lang'] = $lang;
  $secure = defined('COOKIE_SECURE') ? COOKIE_SECURE : false;
  setcookie('lang', $lang, time() + 60*60*24*365, '/', '', $secure, false);
}

function t($key, $vars = []) {
  $lang = get_lang();
  $dict = translations();
  $text = (isset($dict[$lang][$key])) ? $dict[$lang][$key] : ((isset($dict['en'][$key])) ? $dict['en'][$key] : $key);
  foreach ($vars as $k => $v) {
    $text = str_replace('{' . $k . '}', (string)$v, $text);
  }
  return $text;
}

