function format_dt_local($utcIso, $lang = null) {
  if (!$utcIso) return '-';
  $lang = $lang ? $lang : get_lang();
  $locale = locale_for_lang($lang);

  try {
    $dt = new DateTimeImmutable($utcIso, new DateTimeZone('UTC'));
    $tz = isset($_SESSION['browser_timezone']) ? $_SESSION['browser_timezone'] : (isset($_COOKIE['tz']) ? $_COOKIE['tz'] : 'UTC');
    if (!in_array($tz, timezone_identifiers_list(), true)) $tz = 'UTC';
    $dt = $dt->setTimezone(new DateTimeZone($tz));

    if ($lang === 'tr') {
      return $dt->format('d/m/Y H:i');
    }

    if (class_exists('IntlDateFormatter')) {
      $fmt = new IntlDateFormatter($locale, IntlDateFormatter::SHORT, IntlDateFormatter::SHORT, $tz);
      return $fmt->format($dt);
    }
    return $dt->format('Y-m-d H:i');
  } catch (Exception $e) {
    return '-';
  }
}

function format_num_local($value, $lang = null, $decimals = 0) {
  $lang = $lang ? $lang : get_lang();
  $locale = locale_for_lang($lang);

  if (class_exists('NumberFormatter')) {
    $nf = new NumberFormatter($locale, NumberFormatter::DECIMAL);
    $nf->setAttribute(NumberFormatter::FRACTION_DIGITS, $decimals);
    $out = $nf->format($value);
    if ($out !== false) return $out;
  }
  return number_format((float)$value, $decimals, '.', ',');
}

